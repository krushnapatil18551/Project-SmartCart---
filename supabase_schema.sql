-- SmartCart Supabase starter schema. Review before applying to a live project.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price numeric(12,2) not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  rating numeric(2,1) not null default 0,
  image text,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id),
  status text not null default 'Placed' check (status in ('Placed','Confirmed','Shipped','Delivered','Cancelled')),
  payment_status text not null default 'Pending' check (payment_status in ('Pending','Paid','Failed','Pay on delivery','Refunded')),
  payment_method text,
  subtotal numeric(12,2) not null check (subtotal >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  delivery_fee numeric(12,2) not null default 0 check (delivery_fee >= 0),
  total numeric(12,2) not null check (total >= 0),
  address jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0)
);

create table if not exists public.coupons (
  code text primary key,
  discount_type text not null check (discount_type in ('percent','flat')),
  discount_value numeric(12,2) not null check (discount_value > 0),
  min_subtotal numeric(12,2) not null default 0,
  active boolean not null default true,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_activity (
  id bigint generated by default as identity primary key,
  admin_id uuid references auth.users(id),
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'); $$;

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.coupons enable row level security;
alter table public.admin_activity enable row level security;

create policy "profiles read own or admin" on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
create policy "profiles update own or admin" on public.profiles for update to authenticated using (id = auth.uid() or public.is_admin()) with check (id = auth.uid() or public.is_admin());
create policy "active products public read" on public.products for select to anon, authenticated using (active = true or public.is_admin());
create policy "admins insert products" on public.products for insert to authenticated with check (public.is_admin());
create policy "admins update products" on public.products for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admins delete products" on public.products for delete to authenticated using (public.is_admin());
create policy "customers read own orders" on public.orders for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy "customers create own orders" on public.orders for insert to authenticated with check (user_id = auth.uid());
create policy "admin update orders" on public.orders for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "order items own order or admin" on public.order_items for select to authenticated using (exists(select 1 from public.orders o where o.id = order_id and (o.user_id = auth.uid() or public.is_admin())));
create policy "insert items into own order" on public.order_items for insert to authenticated with check (exists(select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()));
create policy "active coupons readable" on public.coupons for select to anon, authenticated using (active = true or public.is_admin());
create policy "admins manage coupons" on public.coupons for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admins read activity" on public.admin_activity for select to authenticated using (public.is_admin());
create policy "admins insert activity" on public.admin_activity for insert to authenticated with check (public.is_admin());

